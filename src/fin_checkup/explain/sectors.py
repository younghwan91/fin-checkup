def group_sector(code: str) -> Sector:
    """묶음 코드(앞 두 자리)에 쓰는 판정 기준. `metrics.sector.sector_for` 와 같은 접두 규칙."""
    if code in FINANCIAL_PREFIXES:
        return Sector.FINANCIAL
    if code in REAL_ESTATE_PREFIXES:
        return Sector.REAL_ESTATE
    return Sector.GENERAL


def peer_group_info(code: str) -> PeerGroupInfo:
    """묶음 코드의 이름·설명. 표에 없는 코드도 페이지가 생기도록 코드 그대로의 이름을 준다."""
    if len(code) != PEER_GROUP_DIGITS:
        raise ValueError(f"업종 묶음 코드는 {PEER_GROUP_DIGITS}자리다: {code!r}")
    name, plain = KSIC_DIVISIONS.get(
        code, (f"업종코드 {code}", "한국표준산업분류 중분류 이름을 아직 붙이지 않은 묶음")
    )
    return PeerGroupInfo(
        code=code,
        name=name,
        plain=plain,
        sector=group_sector(code),
        mixed_note=_HOLDING_NOTE if code == HOLDING_COMPANY_CODE[:PEER_GROUP_DIGITS] else "",
    )
